import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import matter from "gray-matter";

const skillRoot = new URL("../plugins/dossierkit-notes/skills/publish-note/", import.meta.url);
const output = new URL("../src/generated/dossierkit-note-skill.ts", import.meta.url);
const resourcePaths = [
  "SKILL.md",
  "agents/openai.yaml",
  "references/research-quality.md",
  "references/visual-authoring.md"
] as const;

const resources = await Promise.all(resourcePaths.map(async (relativePath) => {
  const text = await readFile(new URL(relativePath, skillRoot), "utf8");
  return {
    uri: `skill://dossierkit-notes/publish-note/${relativePath}`,
    mimeType: relativePath.endsWith(".yaml") ? "application/yaml" : "text/markdown",
    digest: `sha256:${createHash("sha256").update(text, "utf8").digest("hex")}`,
    text
  };
}));

const parsed = matter(resources[0].text);
const frontmatter = Object.fromEntries(Object.entries(parsed.data));
if (frontmatter.name !== "publish-note" || typeof frontmatter.description !== "string") {
  throw new Error("The canonical publish-note Skill must declare name and description frontmatter.");
}

const generated = `// Generated by scripts/generate-mcp-skill.ts from the canonical plugin Skill.\n` +
  `// Do not edit this file directly.\n` +
  `export const DOSSIERKIT_NOTE_SKILL = ${JSON.stringify({
    uri: resources[0].uri,
    frontmatter,
    resources
  }, null, 2)} as const;\n`;

await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(output, generated);
console.log(`Generated MCP Skill catalog with ${resources.length} resources.`);
